export type Lang = "en" | "es";
export const DICTS: Record<Lang, Dict> = { en, es };

export type T = (key: Key, params?: Record<string, string | number>) => string;

export function makeT(lang: Lang): T {
  const d = DICTS[lang] ?? en;
  return (key, params) => {
    // counters: `key.one` is the singular, picked when n is 1
    const one = params?.n === 1 ? (`${key}.one` as Key) : null;
    let s = (one && (d[one] ?? en[one])) || d[key] || en[key] || key;
    if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

export const TIME_ZONE = "Europe/Madrid";

export function locale(lang: Lang): string {
  return lang === "es" ? "es-ES" : "en-GB";
}

export function fmtDate(d: Date, lang: Lang, style: "day" | "dayYear" | "weekday" | "weekdayTime" | "full" | "month" | "time"): string {
  const opts: Intl.DateTimeFormatOptions = { timeZone: TIME_ZONE };
  if (style === "day") Object.assign(opts, { day: "numeric", month: "short" });
  if (style === "dayYear") Object.assign(opts, { day: "numeric", month: "short", year: "numeric" });
  if (style === "weekday") Object.assign(opts, { weekday: "short", day: "numeric" });
  if (style === "weekdayTime") Object.assign(opts, { weekday: "short", day: "numeric", month: "short", hour: "2-digit", minute: "2-digit" });
  if (style === "full") Object.assign(opts, { day: "numeric", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit" });
  if (style === "month") Object.assign(opts, { month: "long" });
  if (style === "time") Object.assign(opts, { hour: "2-digit", minute: "2-digit" });
  return new Intl.DateTimeFormat(locale(lang), opts).format(d).replace(/\.(?=\s|$)/g, "").replace(/,(?=\s\d{1,2}:)/, ",");
}

export function fmtAgo(d: Date, lang: Lang, now = new Date()): string {
  const rtf = new Intl.RelativeTimeFormat(locale(lang), { numeric: "auto" });
  const s = Math.round((d.getTime() - now.getTime()) / 1000);
  const abs = Math.abs(s);
  if (abs < 60) return rtf.format(s, "second");
  if (abs < 3600) return rtf.format(Math.round(s / 60), "minute");
  if (abs < 86400) return rtf.format(Math.round(s / 3600), "hour");
  return rtf.format(Math.round(s / 86400), "day");
}
